#!/usr/bin/env bash
# Builds Codex's global AGENTS.md from the shared Claude rules, so claude/rules/ stays the single source.
# Usage: codex/build-agents-md.sh [output-path]   (default: ~/.codex/AGENTS.md)
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
claude_dir="$repo_dir/claude"
output="${1:-${CODEX_HOME:-$HOME/.codex}/AGENTS.md}"

strip_frontmatter() {
  awk 'NR == 1 && $0 == "---" { in_fm = 1; next } in_fm && $0 == "---" { in_fm = 0; next } !in_fm' "$1"
}

{
  echo "<!-- Generated by codex/build-agents-md.sh from claude/rules. Edit the source, not this file. -->"
  echo
  strip_frontmatter "$claude_dir/CLAUDE.md" | sed '1s/^# .*/# Global Agent Instructions/'
  for rule in "$claude_dir"/rules/*.md; do
    echo
    strip_frontmatter "$rule"
  done
} > "$output.tmp"

mv "$output.tmp" "$output"
echo "Wrote $output ($(wc -c < "$output" | tr -d ' ') bytes)"
